"""
Build a clean, labelled training dataset for the infrastructure-project
early-warning model.

Sources
  real      : MoSPI PAIMANA Flash Report, July 2026 (1775 ongoing + 25 completed)
  synthetic : 1800 records generated by donor-resampling from the real records,
              so marginal and joint distributions stay realistic.

Labels
  delay_label        : 1 if delay_months > 3
  cost_overrun_label : 1 if cost_escalation_pct > 20
"""
import json
import numpy as np
import pandas as pd

RNG = np.random.default_rng(20260729)
REPORT_M = 2026 * 12 + 7          # report month = July 2026, in absolute months
N_SYNTHETIC = 1800


# ----------------------------------------------------------------- helpers
def to_month(s):
    """'MM/YYYY' -> absolute month index."""
    if not isinstance(s, str) or "/" not in s:
        return np.nan
    mm, yy = s.split("/")
    return int(yy) * 12 + int(mm)


def to_iso(mabs):
    if pd.isna(mabs):
        return None
    mabs = int(round(mabs))
    y, m = divmod(mabs - 1, 12)
    return f"{y:04d}-{m + 1:02d}-01"


def norm_state(s):
    s = (s or "").strip()
    if s.startswith("(") or "Multi-State" in s or "," in s:
        return "Multi-States"
    return s


# ----------------------------------------------------------------- real data
def load_real():
    ong = pd.DataFrame(json.load(open("ongoing_raw.json")))
    ong["status"] = "Ongoing"
    ong["actual_doc"] = None

    com = pd.DataFrame(json.load(open("completed_raw.json")))
    com["status"] = "Completed"
    com["physical_progress"] = 100.0

    df = pd.concat([ong, com], ignore_index=True)
    df["state"] = df["state"].map(norm_state)
    df["revised_cost"] = df["revised_cost"].fillna(df["original_cost"])
    df["start_m"] = df["start_date"].map(to_month).fillna(df["approval_date"].map(to_month))
    df["approval_m"] = df["approval_date"].map(to_month)
    df["planned_m"] = df["original_doc"].map(to_month)
    df["revised_m"] = df["revised_doc"].map(to_month)
    df["actual_m"] = df["actual_doc"].map(to_month)
    df["data_source"] = "flash_report_jul2026"
    return df[["project_name", "ministry", "state", "sector", "original_cost",
               "revised_cost", "expenditure", "approval_m", "start_m", "planned_m",
               "revised_m", "actual_m", "physical_progress", "status", "data_source"]]


