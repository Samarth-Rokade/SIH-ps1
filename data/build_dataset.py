def make_name(sector, state, rng):
    tpl = rng.choice(NAME_TEMPLATES.get(sector, ["{name1} infrastructure project, {state}"]))
    a = int(rng.integers(0, 400))
    km = int(rng.integers(8, 220))
    return tpl.format(
        work=rng.choice(WORKS), km=km, a=a, b=a + km, nh=int(rng.integers(2, 966)),
        mode=rng.choice(MODES), plan=rng.choice(PLANS), pkg=int(rng.integers(1, 8)),
        name1=rng.choice(PLACES), name2=rng.choice(PLACES), state=state,
        mty=int(rng.integers(1, 40)), mw=int(rng.integers(1, 25)) * 100,
        kv=rng.choice([220, 400, 765]), beds=int(rng.integers(2, 12)) * 50)


def synthesise(real, n, rng):
    ong = real[real.status == "Ongoing"].reset_index(drop=True)

    # empirical pools used for conditional sampling
    ong = ong.assign(
        planned_dur=(ong.planned_m - ong.start_m),
        overrun=(ong.revised_cost - ong.original_cost) / ong.original_cost,
        exp_ratio=(ong.expenditure / ong.revised_cost).clip(0, 2),
    )
    ong["end_m"] = np.maximum(ong.revised_m.fillna(ong.planned_m), REPORT_M)
    ong["delay"] = (ong.end_m - ong.planned_m).clip(lower=0)

    # sector-level delay behaviour
    sector_delay_rate = ong.groupby("sector").apply(
        lambda g: (g.delay > 3).mean(), include_groups=False).to_dict()
    sector_delay_pool = {s: g.loc[g.delay > 3, "delay"].values
                         for s, g in ong.groupby("sector")}
    sector_states = {s: g.state.value_counts(normalize=True) for s, g in ong.groupby("sector")}

    # progress / expenditure pools bucketed by elapsed fraction
    elapsed_frac = ((REPORT_M - ong.start_m) / ong.planned_dur.replace(0, np.nan)).clip(0, 3)
    ong["bucket"] = pd.cut(elapsed_frac, [-0.01, 0.4, 0.8, 1.2, 99], labels=[0, 1, 2, 3])
    prog_pool = {b: g.physical_progress.values for b, g in ong.groupby("bucket", observed=True)}
    exp_pool = {b: g.exp_ratio.dropna().values for b, g in ong.groupby("bucket", observed=True)}
    # progress conditioned on whether the project is running late
    prog_by_delay = {int(k): g.physical_progress.values
                     for k, g in ong.groupby(ong.delay > 3)}
    ong["pbin"] = pd.cut(ong.physical_progress, [-0.01, 20, 40, 60, 80, 100.01], labels=[0, 1, 2, 3, 4])
    exp_by_prog = {int(k): g.exp_ratio.dropna().values
                   for k, g in ong.groupby("pbin", observed=True)}

    # only use plausible donors so source data-entry errors are not amplified
    ok = (ong.planned_dur.between(6, 180)) & (ong.delay <= 240) & \
         (ong.planned_m.between(2000 * 12, 2045 * 12)) & ong.exp_ratio.notna()
    pool_df = ong[ok].reset_index(drop=True)

    rows = []
    donors = pool_df.sample(n, replace=True, random_state=7).reset_index(drop=True)
    for _, d in donors.iterrows():
        sector, ministry = d.sector, d.ministry
        state = d.state
        if rng.random() < 0.40:
            dist = sector_states[sector]
            state = rng.choice(dist.index.values, p=dist.values)

        # cost: perturb the donor, then draw an escalation from the real pool
        orig = float(np.clip(d.original_cost * np.exp(rng.normal(0, 0.40)), 120, 200000))
        ov = float(rng.choice(pool_df.overrun.values))
        if abs(ov) > 1e-9:                 # preserve the large spike at "no revision"
            ov += rng.normal(0, 0.02)
        rev = max(orig * (1 + float(np.clip(ov, -0.35, 3.0))), 50.0)

        # schedule: inherit the donor's shape so start / duration / slippage stay coupled
        planned_dur = int(np.clip(round(d.planned_dur * rng.uniform(0.85, 1.2)), 6, 180))
        start = int(min(d.start_m + rng.integers(-12, 13), REPORT_M + 6))
        approval = start - int(rng.integers(0, 13))
        planned = start + planned_dur

        if rng.random() < 0.85:                      # keep the donor's delay behaviour
            base = float(d.delay)
            delay = 0 if base == 0 else int(np.clip(round(base * rng.uniform(0.7, 1.4)), 1, 200))
        elif rng.random() < sector_delay_rate.get(sector, 0.5):
            p = sector_delay_pool.get(sector)
            base = float(rng.choice(p)) if p is not None and len(p) else 12.0
            delay = int(np.clip(round(base * rng.uniform(0.7, 1.4)), 4, 200))
        else:
            delay = int(rng.choice([0, 0, 0, 1, 2, 3]))

        completed = rng.random() < 0.18
        # keep each schedule consistent with the way labels are recomputed below
        if completed:
            over = planned + delay - REPORT_M
            if over > 0:                              # must have finished by the report month
                shift = over + int(rng.integers(0, 18))
                start -= shift; approval -= shift; planned -= shift
        elif delay <= 3 and planned + delay < REPORT_M:
            planned = REPORT_M + int(rng.integers(1, 25))   # on-time ⇒ target still ahead
        revised = planned + delay if delay > 0 else np.nan

        # progress drawn from real projects with the same lateness, then the
        # spend ratio from real projects at a similar stage of completion
        late = 1 if (max(planned + delay, REPORT_M) - planned) > 3 else 0
        progress = float(np.clip(rng.choice(prog_by_delay[late]) * rng.uniform(0.9, 1.1), 0, 100))
        pbin = int(np.digitize(progress, [20, 40, 60, 80]))
        exp_ratio = float(np.clip(rng.choice(exp_by_prog[pbin]) * rng.uniform(0.9, 1.1), 0, 1.8))
        if completed:
            status, actual = "Completed", planned + delay
            progress = 100.0
            exp_ratio = float(np.clip(rng.normal(0.97, 0.12), 0.4, 1.6))
        else:
            status, actual = "Ongoing", np.nan

        rows.append({
            "project_name": make_name(sector, state, rng),
            "ministry": ministry, "state": state, "sector": sector,
            "original_cost": round(orig, 2), "revised_cost": round(rev, 2),
            "expenditure": round(rev * exp_ratio, 2),
            "approval_m": approval, "start_m": start, "planned_m": planned,
            "revised_m": revised, "actual_m": actual,
            "physical_progress": round(progress, 2), "status": status,
            "data_source": "synthetic",
        })
    return pd.DataFrame(rows)


# ---------------------------------------------------------------- labelling
def finalise(df):
    df = df.copy()

    # expected / actual finish used for the delay computation
    end = np.where(df.status.eq("Completed"),
                   df.actual_m,
                   np.maximum(df.revised_m.fillna(df.planned_m), REPORT_M))
    df["delay_months"] = np.maximum(end - df.planned_m, 0).round().astype("Int64")
    df["delay_label"] = (df.delay_months > 3).astype(int)

    df["cost_escalation_pct"] = ((df.revised_cost - df.original_cost)
                                 / df.original_cost * 100).round(2)
    df["cost_overrun_label"] = (df.cost_escalation_pct > 20).astype(int)

    # engineered features that are safe to use at prediction time
    df["planned_duration_months"] = (df.planned_m - df.start_m).astype("Int64")
    df["elapsed_months"] = np.maximum(REPORT_M - df.start_m, 0).astype(int)
    df["time_elapsed_pct"] = (df.elapsed_months
                              / df.planned_duration_months.replace(0, pd.NA) * 100).astype(float).round(2)
    df["progress_gap_pct"] = (df.physical_progress - df.time_elapsed_pct).round(2)
    df["expenditure_pct_of_revised_cost"] = (df.expenditure / df.revised_cost * 100).round(2)
    df["project_age_months"] = (REPORT_M - df.approval_m).astype("Int64")

    # data-quality flag for source records with implausible values
    flag = (
        (df.planned_duration_months <= 0)
        | (df.delay_months > 240)
        | (df.planned_m < 2000 * 12) | (df.planned_m > 2045 * 12)
        | (df.expenditure_pct_of_revised_cost > 200)
        | (df.cost_escalation_pct < -50) | (df.cost_escalation_pct > 300)
    )
    df["data_quality_flag"] = flag.fillna(True).astype(int)

    for c, m in [("approval_date", "approval_m"), ("start_date", "start_m"),
                 ("planned_completion", "planned_m"), ("revised_completion", "revised_m"),
                 ("actual_completion", "actual_m")]:
        df[c] = df[m].map(to_iso)

    df.insert(0, "project_id", [f"P{i:05d}" for i in range(1, len(df) + 1)])
    cols = ["project_id", "project_name", "ministry", "state", "sector",
            "original_cost", "revised_cost", "expenditure",
            "approval_date", "start_date", "planned_completion", "revised_completion",
            "actual_completion", "physical_progress", "status",
            "planned_duration_months", "elapsed_months", "time_elapsed_pct",
            "progress_gap_pct", "expenditure_pct_of_revised_cost", "project_age_months",
            "delay_months", "delay_label", "cost_escalation_pct", "cost_overrun_label",
            "data_source", "data_quality_flag"]
    return df[cols]


